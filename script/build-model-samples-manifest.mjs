#!/usr/bin/env node
/**
 * Scan frontend/public/cdn/model_samples/** and emit the TYPED manifest the
 * frontend imports (frontend/src/lib/model-samples.ts): every generated sample
 * set with its cover/icon/example assets AND the prompts that produced them
 * (parsed from the original_prompt.md / example_N.prompt.md files the
 * generation harnesses write). Re-run after generating new sample sets:
 *
 *   node script/build-model-samples-manifest.mjs
 */

import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SAMPLES = path.join(ROOT, "frontend/public/cdn/model_samples");
const OUT = path.join(ROOT, "frontend/src/lib/model-samples.ts");

const exists = (p) => stat(p).then(() => true).catch(() => false);

/** First `> ` blockquote line after a heading matching `re` (or from the top). */
function promptAfter(md, re) {
  const lines = md.split("\n");
  let start = 0;
  if (re) {
    const i = lines.findIndex((l) => re.test(l));
    if (i < 0) return null;
    start = i + 1;
  }
  for (let i = start; i < lines.length; i++) {
    if (re && /^#{1,6} /.test(lines[i]) && i > start) return null; // next section — not found
    const m = lines[i].match(/^>\s?(.*)$/);
    if (m) return m[1].trim();
  }
  return null;
}

function kindOf(title, isVideo, hasInputs) {
  if (/image[- ]edit/i.test(title)) return "image_edit";
  if (/image[- ]to[- ]video/i.test(title)) return "image_to_video";
  if (/text[- ]to[- ]video/i.test(title)) return "text_to_video";
  if (isVideo) return hasInputs ? "image_to_video" : "text_to_video";
  return hasInputs ? "image_edit" : "text_to_image";
}

const sets = [];
for (const kind of ["image_models", "video_models"]) {
  const kindDir = path.join(SAMPLES, kind);
  if (!(await exists(kindDir))) continue;
  for (const slug of (await readdir(kindDir)).sort()) {
    const dir = path.join(kindDir, slug);
    if (!(await stat(dir)).isDirectory()) continue;
    const isVideo = kind === "video_models";
    const base = `/cdn/model_samples/${kind}/${slug}`;
    const set = { slug, isVideo, cover: null, icon: null, coverPrompt: null, iconPrompt: null, examples: [] };

    if (await exists(path.join(dir, "cover_image.webp"))) set.cover = `${base}/cover_image.webp`;
    if (await exists(path.join(dir, "icon_image.webp"))) set.icon = `${base}/icon_image.webp`;
    if (await exists(path.join(dir, "original_prompt.md"))) {
      const md = await readFile(path.join(dir, "original_prompt.md"), "utf8");
      set.coverPrompt = promptAfter(md, /^## cover_image/);
      set.iconPrompt = promptAfter(md, /^## icon_image/);
    }

    const exDir = path.join(dir, "examples");
    if (await exists(exDir)) {
      const files = await readdir(exDir);
      for (const n of [1, 2, 3]) {
        const output = `example_${n}.output.webp`;
        if (!files.includes(output)) continue;
        const inputs = files
          .filter((f) => new RegExp(`^example_${n}\\.input_\\d+\\.webp$`).test(f))
          .sort()
          .map((f) => `${base}/examples/${f}`);
        let prompt = null;
        let title = "";
        const inputPrompts = [];
        const mdName = `example_${n}.prompt.md`;
        if (files.includes(mdName)) {
          const md = await readFile(path.join(exDir, mdName), "utf8");
          title = md.split("\n")[0] ?? "";
          prompt = promptAfter(md, null);
          for (let i = 1; i <= inputs.length; i++) {
            inputPrompts.push(promptAfter(md, new RegExp(`^## input_${i} prompt`)) ?? "");
          }
        }
        set.examples.push({
          id: `example_${n}`,
          kind: kindOf(title, isVideo, inputs.length > 0),
          prompt: prompt ?? "",
          output: `${base}/examples/${output}`,
          inputs,
          inputPrompts,
        });
      }
    }
    if (set.cover || set.icon || set.examples.length) sets.push(set);
  }
}

const ts = `/**
 * GENERATED by script/build-model-samples-manifest.mjs — do not edit by hand.
 * The sample-art library: every generated model sample set with the prompts
 * that produced it. Video-set assets are LOOPING ANIMATED WEBP (play in <img>).
 */

export type SampleKind = "text_to_image" | "image_edit" | "text_to_video" | "image_to_video";

export type SampleExample = {
  id: string;
  kind: SampleKind;
  prompt: string;
  output: string;
  /** Conditioning/edit inputs shown alongside the output, in order. */
  inputs: string[];
  /** The prompts that generated each input (parallel to \`inputs\`). */
  inputPrompts: string[];
};

export type ModelSampleSet = {
  slug: string;
  isVideo: boolean;
  cover: string | null;
  icon: string | null;
  coverPrompt: string | null;
  iconPrompt: string | null;
  examples: SampleExample[];
};

export const MODEL_SAMPLES: Record<string, ModelSampleSet> = ${JSON.stringify(
  Object.fromEntries(sets.map((s) => [s.slug, s])),
  null,
  2,
)};

export function sampleSetFor(slug: string): ModelSampleSet | undefined {
  return MODEL_SAMPLES[slug];
}
`;

await writeFile(OUT, ts);
console.log(`wrote ${OUT} — ${sets.length} sample sets, ${sets.reduce((a, s) => a + s.examples.length, 0)} examples`);
