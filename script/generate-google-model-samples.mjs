/* ── API plumbing ── */

async function apiFetch(pathname, init = {}) {
  const res = await fetch(`${API}${pathname}`, {
    ...init,
    headers: { Authorization: `Bearer ${KEY}`, "Content-Type": "application/json", ...init.headers },
  });
  if (!res.ok) throw new Error(`${init.method ?? "GET"} ${pathname} → ${res.status}: ${await res.text()}`);
  return res.json();
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** Enqueue one generation, poll to terminal, return the first output URL. */
async function runJob(model, body, { pollMs, budgetMs, attempts }) {
  for (let attempt = 1; attempt <= attempts; attempt++) {
    const job = await apiFetch(`/v1/models/${model}/generate`, { method: "POST", body: JSON.stringify(body) });
    const deadline = Date.now() + budgetMs;
    let j = job;
    while ((j.status === "queued" || j.status === "running") && Date.now() < deadline) {
      await sleep(pollMs);
      j = await apiFetch(`/v1/jobs/${job.id}`);
    }
    if (j.status === "succeeded" && j.outputs.length > 0) return { url: j.outputs[0].url, jobId: j.id };
    const msg = j.failure_message ?? j.status;
    console.log(`    ✗ attempt ${attempt}/${attempts} (${j.id}): ${msg}`);
    if (attempt < attempts) await sleep(20_000);
  }
  return null;
}

const genImage = (model, prompt, size, imageInputs) =>
  runJob(
    model,
    { prompt, n: 1, size, quality: "medium", output_format: "webp", ...(imageInputs?.length ? { image_inputs: imageInputs } : {}) },
    { pollMs: 3000, budgetMs: 180_000, attempts: 3 },
  );

const genVideo = (model, prompt, veo, imageInput) =>
  runJob(
    model,
    {
      prompt,
      n: 1,
      ...(veo ? { duration_seconds: 4, resolution: "720p", aspect_ratio: "16:9" } : {}),
      ...(imageInput ? { image_input: imageInput } : {}),
    },
    { pollMs: 10_000, budgetMs: 480_000, attempts: 3 },
  );

async function download(url, dest) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`download ${url} → ${res.status}`);
  await writeFile(dest, Buffer.from(await res.arrayBuffer()));
}

/** Gemini ignores output_format (the router prunes it) and returns big JPEGs —
 * normalize any non-webp "webp" to REAL webp, downscaled for UI weight. */
async function normalizeToWebp(dest, maxWidth) {
  const head = await readFile(dest);
  const isWebp = head.length > 12 && head.toString("ascii", 0, 4) === "RIFF" && head.toString("ascii", 8, 12) === "WEBP";
  if (isWebp) return;
  const tmp = `${dest}.src`;
  await writeFile(tmp, head);
  await execFile("cwebp", ["-quiet", "-q", "82", "-resize", String(maxWidth), "0", tmp, "-o", dest]);
  await rm(tmp, { force: true });
}

/* ── Video → looping animated webp (frames via ffmpeg, assembly via img2webp) ── */

async function mp4ToLoopingWebp(mp4, dest, { width, square }) {
  const frameDir = path.join(TMP, `frames-${path.basename(dest, ".webp")}-${Date.now()}`);
  await mkdir(frameDir, { recursive: true });
  const FPS = 10;
  const vf = square
    ? `fps=${FPS},crop='min(iw,ih)':'min(iw,ih)',scale=${width}:${width}:flags=lanczos`
    : `fps=${FPS},scale=${width}:-2:flags=lanczos`;
  await execFile("ffmpeg", ["-hide_banner", "-loglevel", "error", "-i", mp4, "-an", "-vf", vf, path.join(frameDir, "f_%04d.png")]);
  const { readdir } = await import("node:fs/promises");
  const frames = (await readdir(frameDir)).filter((f) => f.endsWith(".png")).sort().map((f) => path.join(frameDir, f));
  if (frames.length === 0) throw new Error(`no frames extracted from ${mp4}`);
  await execFile("img2webp", ["-loop", "0", "-d", String(Math.round(1000 / FPS)), "-lossy", "-q", "60", ...frames, "-o", dest]);
  await rm(frameDir, { recursive: true, force: true });
}

/* ── Producers (skip-if-exists) ── */

async function produceImage(dest, model, prompt, size, imageInputs, label) {
  if (existsSync(dest)) return console.log(`    ✓ ${label} (exists, skipped)`);
  console.log(`    … ${label}`);
  const r = await genImage(model, prompt, size, imageInputs);
  if (!r) return console.log(`    ✗ ${label} — GAVE UP (re-run to retry)`);
  await download(r.url, dest);
  await normalizeToWebp(dest, size === "1536x1024" ? 1536 : 1024);
  console.log(`    ✓ ${label}  (${r.jobId})`);
}

async function produceVideoWebp(dest, model, prompt, opts, label) {
  if (existsSync(dest)) return console.log(`    ✓ ${label} (exists, skipped)`);
  console.log(`    … ${label} (video render — minutes)`);
  const r = await genVideo(model, prompt, opts.veo, opts.imageInput);
  if (!r) return console.log(`    ✗ ${label} — GAVE UP (re-run to retry)`);
  const mp4 = path.join(TMP, `${model}-${path.basename(dest, ".webp")}.mp4`);
  await mkdir(TMP, { recursive: true });
  await download(r.url, mp4);
  await mp4ToLoopingWebp(mp4, dest, { width: opts.width, square: opts.square });
  await rm(mp4, { force: true });
  console.log(`    ✓ ${label}  (${r.jobId})`);
}

